import { useState } from "react";
import { AlertTriangle, BrainCircuit, Check, CircleDashed, ClipboardCopy, Download, FileJson, Loader2, Play, Save, Square, Video, X, XCircle } from "lucide-react";
import { useReplayStore } from "../../store/useReplayStore";
import { formatClock } from "../../lib/format";
import type { CameraId } from "../../types/security";
import { saveReportLocally, useInvestigatorStore } from "./useInvestigatorStore";
import type { InvestigationReport, ReportMeta } from "./types";

const camName = (c: string) => c.replace("cam", "CAM 0");

/** Seek the existing master timeline (no second clock) and point the dashboard at the supporting camera. */
function jumpTo(t: number, cameraId?: string | null) {
  const r = useReplayStore.getState();
  r.pause();
  r.seek(t);
  if (cameraId) r.selectCamera(cameraId as CameraId);
}

const STATUS_STYLE: Record<string, string> = {
  observed: "border-cyan-400/50 text-cyan-300",
  "human-reviewed": "border-violet-400/50 text-violet-300",
  estimated: "border-amber-400/60 text-amber-300",
  unverified: "border-red-400/60 text-red-300",
};

function download(name: string, text: string, type: string) {
  const url = URL.createObjectURL(new Blob([text], { type }));
  const a = document.createElement("a");
  a.href = url;
  a.download = name;
  a.click();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

function toMarkdown(r: InvestigationReport, m: ReportMeta | null) {
  const L: string[] = [`# ${r.title}`, "", `> DRAFT generated by ${m?.model ?? "NVIDIA Nemotron"} (${m?.toolCalls ?? "?"} tool calls) — requires human review.`, "", "## Summary", r.summary, "", "## Key events"];
  for (const e of r.keyEvents)
    L.push(`- **${formatClock(e.timestamp)}** ${e.title} — ${e.description} _(${e.evidenceStatus}; ${e.cameraIds.map(camName).join(", ") || "no camera"})_`);
  L.push("", "## Camera evidence");
  for (const c of r.cameraEvidence) L.push(`- **${camName(c.cameraId)}**: ${c.summary}`);
  L.push("", "## Uncertainty");
  for (const u of r.uncertainties) L.push(`- ${u.timestamp != null ? `${formatClock(u.timestamp)} ` : ""}${u.description}`);
  L.push("", "## Recommended actions");
  for (const a of r.recommendedActions) L.push(`- [${a.priority}] ${a.action}${a.timestamp != null ? ` (${formatClock(a.timestamp)}${a.cameraId ? `, ${camName(a.cameraId)}` : ""})` : ""}`);
  return L.join("\n");
}

function Section({ title, children, icon }: { title: string; children: React.ReactNode; icon?: React.ReactNode }) {
  return (
    <section className="border-t border-ink-600/70 px-4 py-3">
      <div className="label mb-2 flex items-center gap-1.5">
        {icon}
        {title}
      </div>
      {children}
    </section>
  );
}

function Trace() {
  const trace = useInvestigatorStore((s) => s.trace);
  const status = useInvestigatorStore((s) => s.status);
  const turns = useInvestigatorStore((s) => s.modelTurns);
  if (!trace.length && status !== "running") return null;
  return (
    <Section title={`Agent execution trace · ${trace.length} tool calls · ${turns} model turns`} icon={<BrainCircuit className="h-3 w-3" />}>
      <ol className="space-y-1">
        {trace.map((t, i) => (
          <li key={t.id} className="rounded border border-ink-600/70 bg-ink-850/80 px-2 py-1.5 font-mono text-[10.5px]">
            <div className="flex items-center gap-1.5">
              <span className="w-4 text-right text-slate-500">{i + 1}</span>
              {t.status === "running" ? (
                <Loader2 className="h-3 w-3 animate-spin text-cyan-300" />
              ) : t.status === "ok" ? (
                <Check className="h-3 w-3 text-emerald-400" />
              ) : (
                <XCircle className="h-3 w-3 text-red-400" />
              )}
              <span className="text-cyan-200">{t.name}</span>
              <span className="truncate text-slate-500">{t.args && t.args !== "{}" ? t.args : ""}</span>
              {t.ms != null && <span className="ml-auto shrink-0 text-slate-500">{t.ms} ms</span>}
            </div>
            <div className="mt-0.5 pl-[22px] text-slate-400">{t.status === "running" ? `${t.label}…` : t.summary}</div>
          </li>
        ))}
        {status === "running" && (
          <li className="flex items-center gap-1.5 px-2 py-1 font-mono text-[10.5px] text-slate-400">
            <CircleDashed className="h-3 w-3 animate-spin" /> Nemotron is reasoning over the results…
          </li>
        )}
      </ol>
    </Section>
  );
}

function Report({ r }: { r: InvestigationReport }) {
  const meta = useInvestigatorStore((s) => s.meta);
  const savedAt = useInvestigatorStore((s) => s.savedAt);
  const [copied, setCopied] = useState(false);
  return (
    <>
      <Section title="Incident summary">
        <div className="mb-1 text-[13px] font-medium text-slate-100">{r.title}</div>
        <p className="text-[12px] leading-relaxed text-slate-300">{r.summary}</p>
        <div className="mt-2 rounded border border-amber-400/30 bg-amber-400/5 px-2 py-1 font-mono text-[10px] text-amber-200/90">
          AI DRAFT · requires human review · evidence from structured annotations only (no footage sent to the model)
        </div>
      </Section>
      <Section title={`Key events · click to jump the 3D replay`}>
        <div className="space-y-1.5">
          {r.keyEvents.map((e, i) => (
            <button
              key={i}
              type="button"
              onClick={() => jumpTo(e.timestamp, e.cameraIds[0])}
              className="block w-full rounded-md border border-ink-600 bg-ink-850/80 p-2 text-left transition hover:border-cyan-400/60 hover:bg-cyan-400/5"
            >
              <div className="flex items-center gap-2">
                <span className="font-mono text-[11px] text-cyan-300">{formatClock(e.timestamp)}</span>
                <span className="truncate text-[12px] font-medium text-slate-100">{e.title}</span>
                <span className={`ml-auto shrink-0 rounded border px-1 font-mono text-[9px] uppercase ${STATUS_STYLE[e.evidenceStatus] ?? STATUS_STYLE.unverified}`}>{e.evidenceStatus}</span>
              </div>
              <p className="mt-1 text-[11.5px] leading-snug text-slate-400">{e.description}</p>
              <div className="mt-1 flex flex-wrap gap-1">
                {e.cameraIds.length ? (
                  e.cameraIds.map((c) => (
                    <span key={c} className="inline-flex items-center gap-1 rounded bg-ink-700 px-1 font-mono text-[9.5px] text-slate-300">
                      <Video className="h-2.5 w-2.5" /> {camName(c)}
                    </span>
                  ))
                ) : (
                  <span className="font-mono text-[9.5px] text-amber-300/80">NO CAMERA EVIDENCE</span>
                )}
                {e.evidence.slice(0, 3).map((ref, j) => (
                  <span key={j} className="rounded bg-ink-800 px-1 font-mono text-[9.5px] text-slate-500" title={`${ref.evidenceType} @ ${ref.timestamp}s`}>
                    {ref.eventId ?? ref.evidenceType}
                  </span>
                ))}
              </div>
            </button>
          ))}
        </div>
      </Section>
      {r.cameraEvidence.length > 0 && (
        <Section title="Camera evidence">
          <div className="space-y-1">
            {r.cameraEvidence.map((c) => (
              <div key={c.cameraId} className="flex gap-2 text-[11.5px]">
                <button type="button" onClick={() => c.timestamps[0] != null && jumpTo(c.timestamps[0], c.cameraId)} className="shrink-0 font-mono text-cyan-300 hover:underline">
                  {camName(c.cameraId)}
                </button>
                <span className="text-slate-400">{c.summary}</span>
              </div>
            ))}
          </div>
        </Section>
      )}
      <Section title="Uncertainty & missing evidence" icon={<AlertTriangle className="h-3 w-3 text-amber-300" />}>
        <ul className="space-y-1">
          {r.uncertainties.map((u, i) => (
            <li key={i} className="text-[11.5px] text-amber-100/80">
              {u.timestamp != null && (
                <button type="button" onClick={() => jumpTo(u.timestamp!)} className="mr-1 font-mono text-amber-300 hover:underline">
                  {formatClock(u.timestamp)}
                </button>
              )}
              {u.description}
            </li>
          ))}
          {!r.uncertainties.length && <li className="text-[11.5px] text-slate-500">None reported.</li>}
        </ul>
      </Section>
      <Section title="Recommended actions">
        <ul className="space-y-1">
          {r.recommendedActions.map((a, i) => (
            <li key={i} className="flex gap-2 text-[11.5px] text-slate-300">
              <span className={`shrink-0 font-mono text-[9.5px] uppercase ${a.priority === "high" ? "text-red-300" : a.priority === "medium" ? "text-amber-300" : "text-slate-500"}`}>{a.priority}</span>
              <span>
                {a.action}
                {a.timestamp != null && (
                  <button type="button" onClick={() => jumpTo(a.timestamp!, a.cameraId)} className="ml-1 font-mono text-cyan-300 hover:underline">
                    {formatClock(a.timestamp)}
                  </button>
                )}
              </span>
            </li>
          ))}
        </ul>
      </Section>
      <Section title="Report">
        <div className="flex flex-wrap gap-1.5">
          <SmallBtn onClick={saveReportLocally} icon={<Save className="h-3 w-3" />}>{savedAt ? "SAVED" : "SAVE"}</SmallBtn>
          <SmallBtn
            onClick={() => {
              void navigator.clipboard?.writeText(`${r.title}\n\n${r.summary}`).then(() => {
                setCopied(true);
                setTimeout(() => setCopied(false), 1500);
              });
            }}
            icon={<ClipboardCopy className="h-3 w-3" />}
          >
            {copied ? "COPIED" : "COPY SUMMARY"}
          </SmallBtn>
          <SmallBtn onClick={() => download(`${meta?.incidentId ?? "incident"}-report.json`, JSON.stringify({ meta, report: r }, null, 2), "application/json")} icon={<FileJson className="h-3 w-3" />}>
            JSON
          </SmallBtn>
          <SmallBtn onClick={() => download(`${meta?.incidentId ?? "incident"}-report.md`, toMarkdown(r, meta), "text/markdown")} icon={<Download className="h-3 w-3" />}>
            MARKDOWN
          </SmallBtn>
        </div>
        {meta && (
          <div className="mt-2 font-mono text-[10px] text-slate-500">
            {meta.model} · {meta.toolCalls} tool calls · {meta.turns} turns · {new Date(meta.generatedAt).toLocaleTimeString()}
          </div>
        )}
      </Section>
    </>
  );
}

function SmallBtn({ onClick, icon, children }: { onClick: () => void; icon: React.ReactNode; children: React.ReactNode }) {
  return (
    <button type="button" onClick={onClick} className="inline-flex h-7 items-center gap-1 rounded border border-ink-500/70 bg-ink-800/80 px-2 font-mono text-[10px] text-slate-300 hover:border-cyan-400/60 hover:text-cyan-200">
      {icon}
      {children}
    </button>
  );
}

export function InvestigatorPanel() {
  const open = useInvestigatorStore((s) => s.open);
  const status = useInvestigatorStore((s) => s.status);
  const configured = useInvestigatorStore((s) => s.configured);
  const model = useInvestigatorStore((s) => s.model);
  const error = useInvestigatorStore((s) => s.error);
  const report = useInvestigatorStore((s) => s.report);
  const analyze = useInvestigatorStore((s) => s.analyze);
  const cancel = useInvestigatorStore((s) => s.cancel);
  const setOpen = useInvestigatorStore((s) => s.setOpen);
  if (!open) return null;
  const running = status === "running";
  return (
    <aside className="flex w-[400px] shrink-0 flex-col border-l border-ink-600/70 bg-ink-900/95">
      <div className="flex items-center gap-2 border-b border-ink-600/70 px-4 py-2.5">
        <BrainCircuit className="h-4 w-4 text-[#76b900]" />
        <div className="leading-tight">
          <div className="font-mono text-[12px] font-semibold tracking-[0.18em] text-slate-100">AI INVESTIGATOR</div>
          <div className="font-mono text-[9.5px] text-slate-500">NVIDIA Nemotron · {model ?? "…"}</div>
        </div>
        <button type="button" onClick={() => setOpen(false)} className="ml-auto rounded p-1 text-slate-500 hover:text-slate-200" title="Close">
          <X className="h-4 w-4" />
        </button>
      </div>
      <div className="min-h-0 flex-1 overflow-y-auto">
        <div className="px-4 py-3">
          <button
            type="button"
            disabled={configured === false}
            onClick={running ? cancel : analyze}
            className={`flex h-10 w-full items-center justify-center gap-2 rounded-md border font-mono text-[12px] font-semibold tracking-widest transition disabled:opacity-40 ${
              running ? "border-red-400/60 bg-red-500/10 text-red-200" : "border-[#76b900]/70 bg-[#76b900]/15 text-[#c5ef7a] shadow-[0_0_18px_-6px_rgba(118,185,0,0.9)] hover:bg-[#76b900]/25"
            }`}
          >
            {running ? <Square className="h-3.5 w-3.5" /> : <Play className="h-3.5 w-3.5" />}
            {running ? "STOP" : report ? "RE-ANALYZE INCIDENT" : "ANALYZE INCIDENT"}
          </button>
          <p className="mt-2 text-[11px] leading-snug text-slate-500">
            Nemotron autonomously queries read-only incident tools (events, trajectories, camera evidence, object movements) and drafts an evidence-backed report.
          </p>
          {configured === false && (
            <div className="mt-2 rounded border border-amber-400/40 bg-amber-400/5 p-2 font-mono text-[10.5px] text-amber-200">
              NVIDIA_API_KEY is not configured on the server. Add it to <b>.env</b> (see .env.example) and restart <b>npm run dev</b>.
            </div>
          )}
          {error && (
            <div className="mt-2 rounded border border-red-400/40 bg-red-500/5 p-2 font-mono text-[10.5px] text-red-200">
              Investigation failed: {error}
            </div>
          )}
        </div>
        <Trace />
        {report && <Report r={report} />}
      </div>
    </aside>
  );
}
